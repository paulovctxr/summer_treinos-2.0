import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile,readdir } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const admin='10000000-0000-0000-0000-000000000001';
const team='10000000-0000-0000-0000-000000000002';
const alice='10000000-0000-0000-0000-000000000003';
const bob='10000000-0000-0000-0000-000000000004';
const id='20000000-0000-0000-0000-000000000001';
test('assessment access, account scope, drafts, publication and concurrent edits', async t=>{
  const db=new PGlite();t.after(()=>db.close());
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create schema storage;
    create function storage.allow_any_operation(text[]) returns boolean language sql stable as $$ select true $$;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text,unique(bucket_id,name));
    alter table storage.objects enable row level security;
    create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,deleted_at timestamptz,raw_user_meta_data jsonb default '{}',created_at timestamptz default now());
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth,public to authenticated,anon;
    insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data) values
    ('${admin}','victorpaulognv@gmail.com',now(),'{}'),('${team}','equipe@example.test',now(),'{}'),
    ('${alice}','alice@example.test',now(),'{"name":"Ana Teste","matricula":"1234"}'),('${bob}','bob@example.test',now(),'{"name":"Bruno Teste","matricula":"5678"}');`);
  for(const name of (await readdir(new URL('../supabase/migrations/',import.meta.url))).filter(x=>x.endsWith('.sql')).sort()) await db.exec(await readFile(new URL(`../supabase/migrations/${name}`,import.meta.url),'utf8'));
  const asUser=async(user,role='authenticated')=>db.exec(`reset role;set role ${role};select set_config('request.jwt.claim.sub','${user}',false);`);
  const scalar=async(sql,params=[])=>Object.values((await db.query(sql,params)).rows[0])[0];
  const draft={id,student_id:alice,student_name:'Ana Teste',registration:'1234',instructor:'Professor Teste',assessed_on:'2026-01-01',reassess_on:'2026-04-01',model:'MULHERES',data:{weight:'65',height:'170',notes:'Reavaliação orientada pelo professor'}};
  const save=(record,revision,publish=false)=>scalar('select public.summer_assessment_save($1::jsonb,$2,$3)',[JSON.stringify(record),revision,publish]);
  await asUser('', 'anon');
  await assert.rejects(()=>scalar('select public.summer_assessment_list()'),/permission denied/);
  await asUser(alice);
  await assert.rejects(()=>save(draft,0),/restrito/);
  await assert.rejects(()=>scalar('select public.summer_assessment_find_student(\'5678\')'),/restrito/);
  await assert.rejects(()=>scalar('select public.summer_admin_assessment_account($1,true)',[alice]),/restrito/);
  await assert.rejects(()=>db.query('select * from summer_private.assessments'),/permission denied/);
  await asUser(admin);
  await assert.rejects(()=>scalar('select public.summer_admin_assessment_account($1,true)',[alice]),/exclusiva/);
  await scalar('select public.summer_admin_assessment_account($1,true)',[team]);
  await asUser(team);
  assert.equal(await scalar('select public.summer_is_assessment_team()'),true);
  assert.equal(await scalar('select public.summer_is_admin()'),false);
  assert.equal((await scalar('select public.summer_get_membership()')).status,'inactive');
  await assert.rejects(()=>scalar('select public.summer_admin_set_membership($1,\'suspend\',null)',[alice]),/restrito/);
  const student=await scalar('select public.summer_assessment_find_student(\'1234\')');
  assert.equal(student.id,alice);assert.equal(student.name,'Ana Teste');assert.equal(student.email,undefined);
  const saved=await save(draft,0);assert.equal(saved.revision,1);assert.equal(saved.status,'draft');
  await assert.rejects(()=>save({...draft,data:{height:'1.70'}},1),/faixa/);
  await assert.rejects(()=>save({...draft,data:{fake:'x'}},1),/inválido/);
  await assert.rejects(()=>save({...draft,data:{weight:65}},1),/inválido/);
  await assert.rejects(()=>save({...draft,student_id:bob},1,true),/matrícula/);
  await assert.rejects(()=>save({...draft,instructor:''},1,true),/professor/);
  await assert.rejects(()=>save(draft,0),/Outra pessoa/);
  await save({...draft,data:{weight:'66'}},1);
  await assert.rejects(()=>save(draft,1),/Outra pessoa/);
  await asUser(alice);
  assert.deepEqual(await scalar('select public.summer_assessment_list()'),[]);
  await assert.rejects(()=>scalar('select public.summer_assessment_get($1)',[id]),/indisponível/);
  assert.deepEqual(await scalar('select public.summer_assessment_evolution()'),[]);
  await asUser(team);
  const published=await save(draft,2,true);assert.equal(published.status,'published');assert.equal(published.revision,3);
  await assert.rejects(()=>save(draft,3),/preservada/);
  await asUser(alice);
  assert.equal((await scalar('select public.summer_assessment_get($1)',[id])).data.weight,'65');
  assert.equal((await scalar('select public.summer_assessment_list()')).length,1);
  assert.equal((await scalar('select public.summer_assessment_evolution()'))[0].weight,'65');
  await asUser(bob);
  assert.deepEqual(await scalar('select public.summer_assessment_list()'),[]);
  await assert.rejects(()=>scalar('select public.summer_assessment_get($1)',[id]),/indisponível/);
  await assert.rejects(()=>scalar('select public.summer_assessment_evolution($1)',[alice]),/restrito/);
  const remove=(key,revision)=>scalar('select public.summer_assessment_remove($1,$2)',[key,revision]);
  const removeFolder=(name,records)=>scalar('select public.summer_assessment_remove_folder($1,$2::jsonb)',[name,JSON.stringify(records.map(a=>({id:a.id,revision:a.revision})))]);
  await assert.rejects(()=>remove(id,3),/restrito/);
  await assert.rejects(()=>removeFolder('Professor Teste',[published]),/restrito/);
  await asUser('', 'anon');
  await assert.rejects(()=>remove(id,3),/permission denied/);
  await asUser(team);
  await assert.rejects(()=>db.query('select * from summer_private.assessment_removals'),/permission denied/);
  await assert.rejects(()=>remove(id,2),/mudou/);
  assert.deepEqual(await remove(id,3),{removed:1});
  await assert.rejects(()=>remove(id,3),/mudou/);
  await assert.rejects(()=>save(draft,0),/removida/);
  await asUser(alice);
  assert.deepEqual(await scalar('select public.summer_assessment_list()'),[]);
  assert.deepEqual(await scalar('select public.summer_assessment_evolution()'),[]);
  await assert.rejects(()=>scalar('select public.summer_assessment_get($1)',[id]),/indisponível/);
  await asUser(team);
  const make=(suffix,instructor)=>save({...draft,id:`20000000-0000-0000-0000-${suffix.padStart(12,'0')}`,instructor},0);
  const first=await make('2','João Lima');
  const second=await make('3','\tJOAO  LIMA\t');
  const other=await make('4','Outra Professora');
  await assert.rejects(()=>removeFolder('João Lima',[first]),/mudou/);
  await assert.rejects(()=>removeFolder('João Lima',[first,second,other]),/mudou/);
  await assert.rejects(()=>removeFolder('João Lima',[first,first,second]),/mudou/);
  const changed=await save({...first,data:{weight:'70'}},1);
  await assert.rejects(()=>removeFolder('João Lima',[first,second]),/mudou/);
  assert.equal((await scalar('select public.summer_assessment_list()')).length,3);
  assert.deepEqual(await removeFolder(' joão lima ',[second,changed]),{removed:2});
  assert.deepEqual((await scalar('select public.summer_assessment_list()')).map(a=>a.id),[other.id]);
  await assert.rejects(()=>save(first,0),/removida/);
  const unnamed=await make('5','');
  assert.deepEqual(await removeFolder('',[unnamed]),{removed:1});
  await db.exec('reset role');
  const archived=await db.query('select snapshot,removed_by from summer_private.assessment_removals where id=$1',[id]);
  assert.equal(archived.rows[0].snapshot.data.weight,'65');
  assert.equal(archived.rows[0].removed_by,team);
  await asUser(admin);
  await scalar('select public.summer_admin_assessment_account(null,true)');
  await asUser(team);
  assert.equal(await scalar('select public.summer_is_assessment_team()'),false);
  await assert.rejects(()=>remove(other.id,1),/restrito/);
  await assert.rejects(()=>save({...draft,id:'20000000-0000-0000-0000-000000000002'},0),/restrito/);
  assert.deepEqual(await scalar('select public.summer_assessment_list()'),[]);
});
