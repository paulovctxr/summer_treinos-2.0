import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile,readdir } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const admin='10000000-0000-0000-0000-000000000001';
const team='10000000-0000-0000-0000-000000000002';
const alice='10000000-0000-0000-0000-000000000003';
const bob='10000000-0000-0000-0000-000000000004';
const id='20000000-0000-0000-0000-000000000001';
test('team notifications, trash recovery, training delivery and access isolation', async t=>{
  const db=new PGlite();t.after(()=>db.close());
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create schema storage;
    create function storage.allow_any_operation(text[]) returns boolean language sql stable as $$ select true $$;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text,unique(bucket_id,name));
    alter table storage.objects enable row level security;
    create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,deleted_at timestamptz,raw_user_meta_data jsonb default '{}',created_at timestamptz default now());
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth,public to authenticated,anon;
    insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data) values
    ('${admin}','victorpaulognv@gmail.com',now(),'{}'),('${team}','equipe@example.test',now(),'{}'),
    ('${alice}','alice@example.test',now(),'{"name":"Ana Teste","matricula":"1234"}'),('${bob}','bob@example.test',now(),'{"name":"Bruno Teste","matricula":"5678"}');`);
  for(const name of (await readdir(new URL('../supabase/migrations/',import.meta.url))).filter(x=>x.endsWith('.sql')).sort()) await db.exec(await readFile(new URL(`../supabase/migrations/${name}`,import.meta.url),'utf8'));
  const asUser=async(user,role='authenticated')=>db.exec(`reset role;set role ${role};select set_config('request.jwt.claim.sub','${user}',false);`);
  const scalar=async(sql,params=[])=>Object.values((await db.query(sql,params)).rows[0])[0];

  const assessment={id,student_id:alice,student_name:'Ana Teste',registration:'1234',instructor:'Professor Teste',assessed_on:'2026-01-01',reassess_on:null,model:'MULHERES',data:{weight:'65'}};
  const saveAssessment=(record,revision,publish=false)=>scalar('select public.summer_assessment_save($1::jsonb,$2,$3)',[JSON.stringify(record),revision,publish]);
  const notice=()=>scalar('select public.summer_assessment_notice()');
  const seen=()=>scalar('select public.summer_assessment_seen($1)',[id]);
  const trash=()=>scalar('select public.summer_assessment_trash()');
  const restore=items=>scalar('select public.summer_assessment_restore($1::jsonb)',[JSON.stringify(items)]);
  const getTraining=key=>scalar('select public.summer_training_get($1)',[key]);
  const saveTraining=(record,revision,publish=false)=>scalar('select public.summer_training_save($1::jsonb,$2,$3)',[JSON.stringify(record),revision,publish]);
  const training={id:'30000000-0000-0000-0000-000000000001',student_id:alice,student_name:'Ana Teste',registration:'1234',instructor:'Professor Teste',title:'Adaptação',source_assessment_id:id,notes:'Acompanhamento pelo professor',workouts:[{id:'workout-a',title:'Treino A',focus:'Força',minutes:45,exercises:[{id:'exercise-a',name:'Supino reto',sets:3,reps:'10–12',restSeconds:60,notes:'Controle o movimento'}]}]};
  await asUser('', 'anon');
  await assert.rejects(notice,/permission denied/);
  await assert.rejects(trash,/permission denied/);
  await assert.rejects(()=>saveTraining(training,0),/permission denied/);
  await asUser(admin);await scalar('select public.summer_admin_assessment_account($1,true)',[team]);
  await asUser(team);await saveAssessment(assessment,0,true);
  await assert.rejects(seen,/indisponível/);
  await asUser(alice);assert.deepEqual(await notice(),{unread:1,total:1});
  const opened=await seen();assert.ok(opened);assert.deepEqual(await seen(),opened);assert.deepEqual(await notice(),{unread:0,total:1});
  await assert.rejects(trash,/restrito/);await assert.rejects(()=>restore([]),/restrito/);
  await assert.rejects(()=>saveTraining(training,0),/restrito/);
  await asUser(bob);assert.deepEqual(await notice(),{unread:0,total:0});await assert.rejects(seen,/indisponível/);
  await asUser(team);
  assert.equal(new Date((await scalar('select public.summer_assessment_get($1)',[id])).viewed_at).getTime(),opened.getTime());
  const draft=await saveTraining({...training,workouts:[{...training.workouts[0],exercises:[{...training.workouts[0].exercises[0],sets:0,reps:''}]}]},0);
  assert.equal(draft.status,'draft');
  await asUser(alice);assert.deepEqual(await scalar('select public.summer_training_list()'),[]);await assert.rejects(()=>getTraining(training.id),/indisponível/);
  await asUser(team);
  await assert.rejects(()=>saveTraining(training,0),/mudou/);
  await assert.rejects(()=>saveTraining({...training,student_id:bob,registration:'5678'},1),/outro aluno/);
  await assert.rejects(()=>saveTraining({...training,student_id:bob},1),/matrícula/);
  await assert.rejects(()=>saveTraining(draft,1,true),/séries/);
  await assert.rejects(()=>saveTraining({...training,workouts:[training.workouts[0],training.workouts[0]]},1),/inválido/);
  const invalidExercise=async patch=>assert.rejects(()=>saveTraining({...training,workouts:[{...training.workouts[0],exercises:[{...training.workouts[0].exercises[0],...patch}]}]},1,true));
  await invalidExercise({sets:1.5});await invalidExercise({sets:21});await invalidExercise({restSeconds:-1});await invalidExercise({restSeconds:3601});await invalidExercise({weight:2001});await invalidExercise({weightUnit:'stone'});
  await assert.rejects(()=>saveTraining({...training,starts_on:'2026-11-08',reassess_on:'2026-11-01'},1),/datas/);
  const published=await saveTraining({...training,objective:'Condicionamento',target_zone:'Informada pelo professor',starts_on:'2026-11-08',reviewed_on:'2026-11-08',reassess_on:'2027-01-08'},1,true);assert.equal(published.revision,2);
  assert.equal(published.objective,'Condicionamento');assert.equal(published.starts_on,'2026-11-08');assert.equal(published.reassess_on,'2027-01-08');
  await assert.rejects(()=>saveTraining(training,2),/preservado/);
  await asUser(alice);
  assert.equal((await getTraining(training.id)).workouts[0].exercises[0].sets,3);
  const list=await scalar('select public.summer_training_list()');assert.equal(list.length,1);assert.equal(list[0].workouts,undefined);
  await assert.rejects(()=>db.query('select * from summer_private.training_plans'),/permission denied/);
  await asUser(bob);assert.deepEqual(await scalar('select public.summer_training_list()'),[]);await assert.rejects(()=>getTraining(training.id),/indisponível/);
  await asUser(team);
  await scalar('select public.summer_assessment_remove($1,1)',[id]);
  const removed=(await trash())[0];assert.equal(removed.id,id);assert.equal(removed.data,undefined);
  await asUser(alice);assert.deepEqual(await notice(),{unread:0,total:0});assert.equal((await getTraining(training.id)).status,'published');
  await asUser(team);
  await assert.rejects(()=>restore([{...removed,removed_at:'2020-01-01T00:00:00Z'}]),/mudou/);
  await assert.rejects(()=>restore([removed,removed]),/Selecione/);
  await assert.rejects(()=>restore([removed,{id:'ffffffff-ffff-ffff-ffff-ffffffffffff',removed_at:removed.removed_at}]),/mudou/);
  assert.equal((await trash()).length,1,'failed batch restores must roll back the entire batch');
  assert.deepEqual(await restore([removed]),{restored:1});
  assert.deepEqual(await trash(),[]);
  await assert.rejects(()=>restore([removed]),/mudou/);
  const restored=await scalar('select public.summer_assessment_get($1)',[id]);assert.equal(restored.revision,2);assert.equal(new Date(restored.viewed_at).getTime(),opened.getTime());
  await asUser(alice);assert.deepEqual(await notice(),{unread:0,total:1});
  await asUser(team);
  const draftId='20000000-0000-0000-0000-000000000002';
  await saveAssessment({...assessment,id:draftId},0);
  await scalar('select public.summer_assessment_remove_folder($1,$2::jsonb)',['Professor Teste',JSON.stringify([{id,revision:2},{id:draftId,revision:1}])]);
  assert.equal((await trash()).length,2);assert.deepEqual(await restore(await trash()),{restored:2});
  await assert.rejects(()=>saveAssessment({...assessment,id:draftId},1),/Outra pessoa/);
  await asUser(alice);assert.equal((await scalar('select public.summer_assessment_list()')).length,1);
  await asUser(admin);await scalar('select public.summer_admin_assessment_account(null,true)');
  await asUser(team);await assert.rejects(trash,/restrito/);await assert.rejects(()=>restore([]),/restrito/);await assert.rejects(()=>saveTraining(training,2),/restrito/);
  assert.deepEqual(await scalar('select public.summer_training_list()'),[]);
});
